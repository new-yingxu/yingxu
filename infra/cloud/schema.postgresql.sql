-- Apply schema.postgresql.v2-access.sql immediately after this file, before adding user data.
CREATE TABLE IF NOT EXISTS schema_migrations (
  version INTEGER PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS devices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id VARCHAR(160) NOT NULL,
  device_id VARCHAR(500) NOT NULL,
  origin VARCHAR(16) NOT NULL,
  display_name VARCHAR(120) NOT NULL DEFAULT '',
  revoked BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL,
  last_seen_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT uq_device_owner_id UNIQUE (owner_id, device_id)
);
CREATE INDEX IF NOT EXISTS ix_devices_owner_id ON devices (owner_id);

CREATE TABLE IF NOT EXISTS sync_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id VARCHAR(160) NOT NULL,
  device_id VARCHAR(500) NOT NULL,
  event_id VARCHAR(500) NOT NULL,
  sequence BIGINT NOT NULL,
  body_json JSON NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT uq_sync_owner_event UNIQUE (owner_id, event_id),
  CONSTRAINT uq_sync_device_sequence UNIQUE (owner_id, device_id, sequence)
);
CREATE INDEX IF NOT EXISTS ix_sync_events_owner_id ON sync_events (owner_id);
CREATE INDEX IF NOT EXISTS ix_sync_events_device_id ON sync_events (device_id);

CREATE TABLE IF NOT EXISTS agent_actions (
  id VARCHAR(500) NOT NULL,
  owner_id VARCHAR(160) NOT NULL,
  device_id VARCHAR(500) NOT NULL,
  origin VARCHAR(16) NOT NULL,
  tool VARCHAR(64) NOT NULL,
  state VARCHAR(40) NOT NULL,
  proposal_json JSON NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT pk_agent_actions PRIMARY KEY (owner_id, id)
);
CREATE INDEX IF NOT EXISTS ix_agent_actions_owner_id ON agent_actions (owner_id);

CREATE TABLE IF NOT EXISTS sync_preferences (
  owner_id VARCHAR(160) PRIMARY KEY,
  sync_records BOOLEAN NOT NULL DEFAULT TRUE,
  sync_agent_sessions BOOLEAN NOT NULL DEFAULT TRUE,
  sync_thumbnails BOOLEAN NOT NULL DEFAULT FALSE,
  sync_paths BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL
);

INSERT INTO schema_migrations (version, applied_at)
VALUES (1, CURRENT_TIMESTAMP)
ON CONFLICT (version) DO NOTHING;

